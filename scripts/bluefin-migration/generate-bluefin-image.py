def categorize(pkg: str) -> tuple:
    """Return (fedora_name_or_None, category) prioritizing availability."""
    if pkg in FLATPAK_PACKAGES and FLATPAK_PACKAGES[pkg]:
        return (None, "FLATPAK")
    if pkg in BREW_PACKAGES:
        return (None, "BREW")
    if pkg in CARGO_PACKAGES:
        return (None, "CARGO")
    if pkg in PIP_PACKAGES:
        return (None, "PIP")
    if pkg in GO_PACKAGES:
        return (None, "GO")
    if pkg in UNAVAILABLE:
        return (None, "UNAVAILABLE")
    mapped = FEDORA_RENAME.get(pkg)
    if mapped is not None:
        return (mapped, "RPM")
    return (pkg, "RPM")


def build_containerfile(packages):
    """Generate Containerfile for custom Bluefin image."""
    rpm_packages = set()
    flatpak_refs = set()
    brew_packages = set()
    cargo_packages = set()
    pip_packages = set()
    go_packages = set()
    unavailable = set()
    # Track alternative install methods for unavailable packages
    unavailable_notes = {}

    def collect(pkg_list):
        for pkg in pkg_list:
            if isinstance(pkg, str):
                fedora_name, cat = categorize(pkg)
                if cat == "RPM" and fedora_name:
                    rpm_packages.add(fedora_name)
                elif cat == "FLATPAK":
                    ref = FLATPAK_PACKAGES.get(pkg)
                    if ref:
                        flatpak_refs.add(ref)
                elif cat == "BREW":
                    brew_packages.add(pkg)
                elif cat == "CARGO":
                    cargo_packages.add(pkg)
                elif cat == "PIP":
                    pip_packages.add(pkg)
                elif cat == "GO":
                    go_packages.add(pkg)
                elif cat == "UNAVAILABLE":
                    unavailable.add(pkg)

    for category in packages:
        collect(packages[category])
    if "aur" in packages:
        collect(packages["aur"])

    rpm_sorted = sorted(rpm_packages)
    flatpak_sorted = sorted(flatpak_refs)
    brew_sorted = sorted(brew_packages)
    cargo_sorted = sorted(cargo_packages)
    pip_sorted = sorted(pip_packages)
    go_sorted = sorted(go_packages)
    unavailable_sorted = sorted(unavailable)

    lines = []
    lines.append("# Generated Bluefin custom image Containerfile")
    total = len(rpm_sorted) + len(flatpak_sorted) + len(brew_sorted) + len(cargo_sorted) + len(pip_sorted) + len(go_sorted)
    lines.append(f"# Source packages: {total} mapped + {len(unavailable_sorted)} unavailable")
    lines.append(f"#   RPM: {len(rpm_sorted)}  Flatpak: {len(flatpak_sorted)}  Brew: {len(brew_sorted)}")
    lines.append(f"#   Cargo: {len(cargo_sorted)}  Pip: {len(pip_sorted)}  Go: {len(go_sorted)}")
    lines.append("")
    lines.append("FROM ghcr.io/ublue-os/bluefin-dx:latest")
    lines.append("")
    lines.append("# ── Enable RPM Fusion ───────────────────────────────────────")
    lines.append("RUN rpm-ostree install -y \\")
    lines.append("    https://mirrors.rpmfusion.org/free/fedora/rpmfusion-free-release-$(rpm -E %fedora).noarch.rpm \\")
    lines.append("    https://mirrors.rpmfusion.org/nonfree/fedora/rpmfusion-nonfree-release-$(rpm -E %fedora).noarch.rpm")
    lines.append("")

    # RPM packages
    lines.append(f"# ── RPM packages ({len(rpm_sorted)} total) ──────────────────")
    for i in range(0, len(rpm_sorted), 6):
        batch = rpm_sorted[i:i+6]
        lines.append("RUN rpm-ostree install -y \\")
        for j, p in enumerate(batch):
            suffix = " \\" if (i + j < len(rpm_sorted) - 1 and j == len(batch) - 1) else ""
            lines.append(f"    {p}{suffix}")
        if i + len(batch) < len(rpm_sorted):
            lines.append("")

    # Flatpak
    if flatpak_sorted:
        lines.append("")
        lines.append(f"# ── Flatpak apps ({len(flatpak_sorted)} total) ─────────────")
        lines.append("RUN flatpak remote-add --if-not-exists flathub https://flathub.org/repo/flathub.flatpakrepo")
        for ref in flatpak_sorted:
            lines.append(f"RUN flatpak install -y flathub {ref}")

    # Brew
    if brew_sorted:
        lines.append("")
        lines.append(f"# ── Homebrew ({len(brew_sorted)} total) ─────────────────────")
        lines.append("# Homebrew is pre-installed in Bluefin DX")
        for pkg in brew_sorted:
            lines.append(f"RUN brew install {pkg}")

    # Cargo
    if cargo_sorted:
        lines.append("")
        lines.append(f"# ── Cargo ({len(cargo_sorted)} total) ───────────────────────")
        lines.append("# cargo-binstall is recommended for speed")
        for pkg in cargo_sorted:
            lines.append(f"RUN cargo binstall -y {pkg} || cargo install {pkg}")

    # Pip
    if pip_sorted:
        lines.append("")
        lines.append(f"# ── Pip/Pipx ({len(pip_sorted)} total) ──────────────────────")
        for pkg in pip_sorted:
            lines.append(f"RUN pipx install {pkg}")

    # Go
    if go_sorted:
        lines.append("")
        lines.append(f"# ── Go ({len(go_sorted)} total) ─────────────────────────────")
        for pkg in go_sorted:
            lines.append(f"RUN go install github.com/{pkg}@latest")

    # Unavailable
    if unavailable_sorted:
        lines.append("")
        lines.append(f"# ── UNAVAILABLE ({len(unavailable_sorted)} total) ────────────")
        lines.append("# No Fedora/Flathub/Brew/Cargo/Pip/Go equivalent found.")
        lines.append("# Must compile from source, find COPR, or skip.")
        for p in unavailable_sorted:
            lines.append(f"#   - {p}")

    return "\n".join(lines)


