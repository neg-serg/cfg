def build_mapping(packages):
    all_packages = []
    def collect(pkg_list, source):
        for p in pkg_list:
            if isinstance(p, str):
                fedora, cat = categorize(p)
                all_packages.append({"arch": p, "fedora": fedora, "source": cat, "category": source})
    for cat in packages:
        collect(packages[cat], cat)
    if "aur" in packages:
        collect(packages["aur"], "aur")
    return yaml.dump(all_packages, sort_keys=False, allow_unicode=True, default_flow_style=False)


def build_missing(packages):
    missing = set()
    def collect(pkg_list):
        for p in pkg_list:
            if isinstance(p, str):
                _, cat = categorize(p)
                if cat == "UNAVAILABLE":
                    missing.add(p)
    for cat in packages:
        collect(packages[cat])
    if "aur" in packages:
        collect(packages["aur"])
    return "\n".join(sorted(missing))


def main():
    packages = load_packages()
    outdir = Path(__file__).resolve().parent

    # Containerfile
    cf = build_containerfile(packages)
    (outdir / "Containerfile").write_text(cf)
    print(f"Wrote Containerfile ({len(cf.splitlines())} lines)")

    # flatpak.list
    fl = build_flatpak_list(packages)
    (outdir / "flatpak.list").write_text(fl + "\n")
    print(f"Wrote flatpak.list ({len(fl.splitlines())} lines)")

    # brew.Brewfile
    bf = build_brewfile(packages)
    (outdir / "brew.Brewfile").write_text(bf + "\n")
    print(f"Wrote brew.Brewfile ({len(bf.splitlines())} lines)")

    # cargo.list
    cl = build_cargo_list(packages)
    (outdir / "cargo.list").write_text(cl + "\n")
    print(f"Wrote cargo.list ({len(cl.splitlines())} lines)")

    # pip.list
    pl = build_pip_list(packages)
    (outdir / "pip.list").write_text(pl + "\n")
    print(f"Wrote pip.list ({len(pl.splitlines())} lines)")

    # mapping.yaml
    mp = build_mapping(packages)
    (outdir / "mapping.yaml").write_text(mp)
    print(f"Wrote mapping.yaml ({len(mp.splitlines())} lines)")

    # missing.txt
    ms = build_missing(packages)
    (outdir / "missing.txt").write_text(ms + "\n")
    print(f"Wrote missing.txt ({len(ms.splitlines())} lines)")

    print(f"\nDone. Files in {outdir}/")


if __name__ == "__main__":
    main()
